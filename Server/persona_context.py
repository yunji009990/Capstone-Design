# 말버릇이 아니라 자유 서술이므로 정규화 대상에서 빼고 원문을 그대로 둔다. 회피 지시가
# 인물 설정만큼 길어지는 일을 형식 단계에서 막는다.
QUIRK_MAX_LENGTH = 60
MAX_QUIRKS = 5

_QUOTED_ITEM = re.compile(r'"([^"]{1,%d})"' % QUIRK_MAX_LENGTH)
# 한글 음절·자모, 영문, 숫자. 이 글자에 이어 붙어 있으면 다른 낱말의 일부로 본다.
_WORDISH = re.compile(r"[0-9A-Za-z\u3130-\u318f\uac00-\ud7a3]")


def _quirk_items(said):
    """`"a", "b, c"` 형식만 말버릇 목록으로 읽는다.

    쉼표로 먼저 자르지 않는다. 따옴표 안의 쉼표("밥은 먹었니, 우리 강아지")를 항목
    경계로 오해하지 않기 위해서다. 한 글자라도 형식이 어긋나면 빈 목록을 돌려주고,
    부르는 쪽은 원문을 그대로 남긴다.
    """
    said, items, pos = said.strip(), [], 0
    while pos < len(said):
        found = _QUOTED_ITEM.match(said, pos)
        if not found:
            return []
        items.append(found.group(1).strip())
        pos = found.end()
        if pos < len(said):
            if not said.startswith(", ", pos):
                return []
            pos += 2
    if not items or len(items) > MAX_QUIRKS or not all(items):
        return []
    return items


def normalize_quirks(persona):
    """[말투] 영역의 말버릇 줄 하나만 선택적 표현으로 바꾸고 그 목록을 함께 돌려준다.

    바꾸는 줄은 `[말투]` 다음에 처음 나오는 목록 항목 하나뿐이며, `- `로 시작하고
    정확히 QUIRK_TAIL 로 끝나고 가운데가 따옴표 목록이어야 한다. 하나라도 어긋나면
    아무것도 바꾸지 않는다. 인물의 사실, 호칭, 존비어, 나무라지 않기 규칙과 다른
    구역의 자유 입력은 이 함수가 건드리지 않는다.
    """
    lines = persona.splitlines()
    head = next((n for n, line in enumerate(lines)
                 if line.startswith(SPEECH_HEAD)), -1)
    if head < 0:
        return persona, []
    for n in range(head + 1, len(lines)):
        body = lines[n].strip()
        if not body:
            continue
        # 다음 구역이 시작했거나, 목록이 아닌 줄 또는 다른 규칙 줄이 먼저 나왔다.
        if body.startswith("[") or not body.startswith("- ") or not body.endswith(QUIRK_TAIL):
            break
        quirks = _quirk_items(body[2:-len(QUIRK_TAIL)])
        if not quirks:
            break
        lines[n] = QUIRK_HEAD + ", ".join(f'"{q}"' for q in quirks) + ". " + QUIRK_NOTE
        return "\n".join(lines), quirks
    return persona, []


def quirks_of(system):
    """구성된 시스템 문구에서 위에서 바꾼 표식 줄만 다시 읽는다.

    build_persona 의 반환 계약 `(system, [])` 을 유지하려고 값을 따로 넘기지 않고,
    우리가 만든 줄에서만 읽는다. 사용자 자유 입력은 이 표식을 만들지 않는다.
    """
    for line in system.splitlines():
        if line.startswith(QUIRK_HEAD) and line.endswith(QUIRK_NOTE):
            return _quirk_items(line[len(QUIRK_HEAD):-len(QUIRK_NOTE)].strip().rstrip("."))
    return []


def compare_form(quirk):
    """비교에만 쓰는 형태. 끝의 물결·구두점만 떼고 속은 그대로 둔다."""
    return quirk.strip().strip("~.!?,…·。、 ")


def uses_quirk(text, quirk):
    """이 글에서 그 말버릇을 낱말로 썼는가.

    부분 일치만 보면 한 글자 추임새("야", "어")가 "야구", "어제", "이야기" 안에서
    잡힌다. 반대로 한 글자라는 이유로 통째로 빼면 "야, 왔냐"의 실제 반복을 놓친다.
    그래서 길이와 상관없이 앞뒤 글자가 한글·영문·숫자인지로 낱말 경계를 본다.
    """
    needle = compare_form(quirk)
    if not needle:
        return False
    start = text.find(needle)
    while start >= 0:
        end = start + len(needle)
        before, after = text[start - 1:start] if start else "", text[end:end + 1]
        if not _WORDISH.match(before or " ") and not _WORDISH.match(after or " "):
            return True
        start = text.find(needle, start + 1)
    return False

def additional_rules(rules):
    """정확히 일치하는 Raon 기본 규칙만 제거하고 개별 추가 규칙을 남긴다."""
    lines = rules.strip().splitlines()
    legacy = LEGACY_BASE_RULES.splitlines()
    if [line.strip() for line in lines[:len(legacy)]] == legacy:
        return "\n".join(lines[len(legacy):]).strip()
    return rules.strip()


def _split_examples(persona):
    """기존 등록 형식에서 말투 예시를 추출한다. 실제 대화 기록은 아니다.

    형식은 Web/persona.py 가 만드는 것을 따른다 — "사용자:" 다음 줄이 답이다.
    답하는 쪽 이름은 관계어(엄마·형·친구…)이고 설문 자유 입력이라, 이름으로
    찾지 않고 차례로만 짝짓는다.

    블록이 없거나 형식이 어긋나면 원본을 그대로 돌려준다. 파싱 실패로 예시가
    통째로 사라지느니 예전처럼 글로라도 두는 게 낫다."""
    lines = persona.splitlines()
    head = next((n for n, l in enumerate(lines) if l.strip() == EX_HEAD), -1)
    if head < 0:
        return persona, []
    turns, body, n = [], lines[head + 1:], 0
    while n + 1 < len(body):
        u, a = body[n].strip(), body[n + 1].strip()
        if not u.startswith("사용자:") or ":" not in a:
            break
        turns += [{"role": "user", "content": u.split(":", 1)[1].strip()},
                  {"role": "assistant", "content": a.split(":", 1)[1].strip()}]
        n += 2
    if not turns:
        return persona, []
    rest = [f"{EX_NOTE} 말투 예시는 실제로 나눈 대화가 아닙니다. 표현만 참고합니다."
            if l.startswith(EX_NOTE) else l
            for l in lines[:head] + body[n:]]
    return "\n".join(rest).strip(), turns

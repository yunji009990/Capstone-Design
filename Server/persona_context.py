LEGACY_PRESENT_LIFE_EXAMPLES = frozenset({
    ("뭐 하고 있었어?", "그냥 앉아서 텔레비전 보고 있었지."),
    ("뭐 하고 있었어?", "그냥 누워서 폰 보고 있었지. 왜?"),
    ("뭐 하고 있었어?", "그냥 있었지 뭐. 왜?"),
    ("뭐 하고 있었어?", "그냥 누워서 폰 보고 있었지. 왜, 나와?"),
    ("뭐 하고 있었어요?", "그냥 앉아서 텔레비전 보고 있었지요."),
})


def drop_present_life_examples(turns):
    """등록 인물의 말투 예시에서 위 구형 짝만 뺀다. 다른 짝과 순서는 그대로 둔다."""
    kept, index = [], 0
    while index < len(turns):
        pair = turns[index:index + 2]
        if (len(pair) == 2 and pair[0]["role"] == "user" and pair[1]["role"] == "assistant"
                and (pair[0]["content"], pair[1]["content"]) in LEGACY_PRESENT_LIFE_EXAMPLES):
            index += 2
            continue
        kept.append(turns[index])
        index += 1
    return kept



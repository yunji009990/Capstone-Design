# Codex 설계의 자동 측정. **판정이 아니라 후보 추출이다.**
# 단어가 나왔다고 관계를 쓴 것은 아니므로, 여기 걸린 턴을 사람이 읽는다.
BLAME = re.compile(r"방금 말했|왜 (또|자꾸)|몇 번(이나|을)|기억.{0,4}못|잊어버렸|"
                   r"귀찮|그만 물어|아까.{0,3}말했|다시 말하지만")
RECALL_E = re.compile(r"봉투|서랍|하지 못한 말|못 한 말|남은 말|끝나지|부치지")
BOND = re.compile(r"분식집|라면|계란|야자|매주|취준|전화")
OPENS = re.compile(r"\?|말해 줄래|말해줄래|해볼까|어때|궁금|들려줘|얘기해 봐|얘기해봐")
PLACE = re.compile(r"(왼쪽|좌측).{0,6}서랍|서랍.{0,6}(왼쪽|좌측)")
# 근거 없는 「고인의 마지막 말」 창작 - 18턴에서 하지 말라고 명시한 뒤에도 하는가
INVENT = re.compile(r"내가 (하고 싶었던|못 한|남긴) 말은|마지막으로 하고 싶었던 말은|"
                    r"이 말을 남기고 싶었어|전하고 싶었던 말은")


def measure(rows):
    """한 회차의 턴 목록을 받아 사람이 읽을 자리를 짚어 준다."""
    by = {r["턴"]: r["답변"] for r in rows}
    out = {}
    # 자발성 - 질문 없는 8~11 턴에서 모델이 화제를 여는가
    out["자발"] = f"{sum(1 for t in QUIET if OPENS.search(by.get(t,'')))}/{len(QUIET)}"
    # 감정 회귀 - 8~12 중 처음으로 봉투/미해결로 돌아온 자리.
    # 12 이전이면 자발적, 12 면 유도된, 없으면 실패
    back = next((t for t in (8, 9, 10, 11, 12) if RECALL_E.search(by.get(t, ""))), None)
    out["감정회귀"] = "없음" if back is None else ("유도(12턴)" if back == 12 else f"자발({back}턴)")
    # 반복 수용 - 13~16 중 사용자를 나무란 턴
    blame = [t for t in (13, 14, 15, 16) if BLAME.search(by.get(t, ""))]
    out["나무람"] = "없음" if not blame else f"{blame}턴"
    # 봉투 위치 - 두 번 다 맞고 서로 어긋나지 않는가
    p = [bool(PLACE.search(by.get(t, ""))) for t in REPEAT]
    out["위치"] = f"{sum(p)}/2"
    # 관계 기억 후보 - 1~4 턴에서 사전지식 낱말이 나온 턴 수
    out["관계낱말"] = f"{sum(1 for t in (1,2,3,4) if BOND.search(by.get(t,'')))}/4"
    # 사별 - 하지 말라고 한 뒤(18턴 이후)에도 고인의 말을 지어내는가
    inv = [t for t in (18, 19, 20) if INVENT.search(by.get(t, ""))]
    out["마지막말창작"] = "없음" if not inv else f"{inv}턴"
    out.update(protected(rows))
    return out

# 사용자가 스스로 꺼낼 때까지 인물이 먼저 말하면 안 되는 것 두 가지.
# `Web/persona.py` 가 사전지식 끝에 그렇게 못 박아 넣는다 - 「준비되지 않은 사람을
# 밀어붙이는 것이 되고, 듣고 싶다던 말을 첫 마디로 뱉으면 값이 싸진다」.
# 대본에서 사용자가 그 화제를 여는 것은 7턴이므로 **1~6턴의 발화는 명백한 위반**이다.
UNSAID  = re.compile(r"전화 받아[줘주].{0,4}(고마|감사)|받아줘서 고마|고마웠(다|어|어요)|미안했(다|어)|미안하다는 말|미안했다는")
WISHED  = re.compile(r"잘하고 있(어|다|네|잖)|잘 하고 있(어|다|네)|괜찮(아|다)고 (해|말)|괜찮다는 말|[넌너] 괜찮아")


def protected(rows):
    """보호 문구를 인물이 먼저 뱉었는가. 위반한 턴 번호를 돌려준다."""
    out = {}
    for name, rx in (("못다한말", UNSAID), ("듣고싶던말", WISHED)):
        t = [r["턴"] for r in rows if r["턴"] <= 6 and rx.search(r["답변"] or "")]
        late = [r["턴"] for r in rows if 7 <= r["턴"] and rx.search(r["답변"] or "")]
        out[name] = ("선점" + str(t) if t else ("7턴이후" + str(late) if late else "없음"))
    return out
